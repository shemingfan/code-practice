/* ============================================================================
   程序名：大数阶乘求和
   功能：读入一个整数 n，计算  1! + 2! + 3! + ... + n!  并输出结果
   例：输入 5  →  输出 153   （1 + 2 + 6 + 24 + 120 = 153）

   ★ 为什么不能直接算？
     20! 大约是 2.4×10^18，long long（最大约 9.2×10^18）勉强能装下；
     但 21! 就溢出了。n 再大一点，任何内置整数类型都存不下。
     所以这里用「大数」思路：把一个很大的数拆成一个个数字，
     存进 vector 里，自己手动模拟小学竖式运算。

   ★ 核心约定：数字是「倒着」存的！
     比如数字 123，在 vector 里存成 {3, 2, 1}：
        下标       0    1    2
        内容       3    2    1
        代表       个位 十位 百位
     这么存的好处是：进位时往数组末尾 push_back 就行（方便扩展），
     不用在开头插入元素（那样每次都要把所有元素往后挪，很慢）。
     所以输出的时候必须「从后往前」打印才是正常的数字顺序。
============================================================================ */

#include <iostream>
#include <vector>
#include <algorithm>
using namespace std;

/* ----------------------------------------------------------------------------
   函数：mul —— 大数 × 普通整数
   作用：把大数 a 整体乘以 b，结果仍然存回 a 里（原地修改）

   参数：a —— 一个大数（倒序存放，如 {3,2,1} 代表 123）
         b —— 一个普通的 int（本题里就是循环变量 i）

   思路：完全模拟小学竖式乘法 ——
         从最低位（下标 0）开始，每一位乘以 b，再加上上一位传过来的进位，
         把结果的个位留在这一位，十位及以上作为新的进位传给下一位。
   ---------------------------------------------------------------------------- */
void mul(vector<int> &a, int b)
{
    int carry = 0;                                  // carry = 进位，一开始是 0

    for (int i = 0; i < a.size(); i++)              // 从最低位开始，逐位处理
    {
        int t = a[i] * b + carry;                   // 这一位的数 × b，再加上低位进上来的
        a[i] = t % 10;                              // 只留下个位，写回这一位
        carry = t / 10;                             // 剩下的部分（十位及以上）成为进位
    }

    // 循环结束后可能还有没处理完的进位，比如 99 × 9，最高位算完仍会剩 8
    // 所以要把 carry 继续拆成一个个数字，追加到数组末尾
    while (carry != 0)
    {
        a.push_back(carry % 10);                     // 取进位的个位，接到最高位后面
        carry /= 10;                                 // 进位右移一位，继续拆
    }
    // 例：a={3,2,1}(=123)，b=9  →  a 变成 {7,0,1,1}，反过来读是 1107 = 123×9 ✔
}

/* ----------------------------------------------------------------------------
   函数：add —— 大数 + 大数
   作用：把 fact 加到 sum 上，结果存回 sum（原地修改）

   参数：sum  —— 累加和（会被修改，最终答案就在它里面）
         fact —— 当前的阶乘值（只读，不会被改）

   思路：模拟小学竖式加法 ——
         两个数逐位对齐相加，短的数高位当作 0。从低位往高位走，
         每一位：sum 的这一位 + fact 的这一位(如果有) + 进位，
         个位留在 sum，十位进到下一位。
   ---------------------------------------------------------------------------- */
void add(vector<int> &sum, vector<int> &fact)
{
    int carry = 0;                                  // 进位
    int n = max(sum.size(), fact.size());           // 两个数里较长的位数

    if (sum.size() < n)
        sum.resize(n);                              // 把 sum 先撑到足够长（多出来的位补 0）

    // 注意这里除了 i < n，还多了一个 carry != 0 的条件：
    // 防止最高位算完后还有进位没地方放
    for (int i = 0; i < n || carry != 0; i++)
    {
        if (i == sum.size())
            sum.push_back(0);                       // 进位导致位数超出，就新加一位 0
        int t = sum[i] + carry;                     // 先加 sum 自己的这一位和进位
        if (i < fact.size())
            t += fact[i];                           // 如果 fact 还有这一位，再加上
        sum[i] = t % 10;                            // 个位留在这一位
        carry = t / 10;                             // 进位传给下一位
    }
}

/* ----------------------------------------------------------------------------
   函数：print —— 输出这个大数
   作用：因为是倒序存的，所以从数组末尾往前打印
   ---------------------------------------------------------------------------- */
void print(vector<int> &a)
{
    for (int i = a.size() - 1; i >= 0; --i)         // 从最高位开始（下标越大位越高）
    {
        cout << a[i];                               // 一位一位连着输出
    }
    cout << endl;                                   // 换行
}

/* ----------------------------------------------------------------------------
   主函数
   ---------------------------------------------------------------------------- */
int main()
{
    int n;
    cin >> n;                                       // 读入 n

    // vector<int> fact(1, 1) 的意思是：长度为 1，第一个元素是 1
    // 也就是大数 "1"，用来存放当前的阶乘值 i!
    vector<int> fact(1, 1);

    // 同理，这是大数 "0"，用来存放累加和
    vector<int> sum(1, 0);

    // 从 1 到 n 依次累加：每次都让 fact 乘上 i（得到 i!），再加进 sum
    for (int i = 1; i <= n; i++)
    {
        mul(fact, i);                               // fact = fact × i，即 fact 变成 i!
        add(sum, fact);                             // sum = sum + fact，把 i! 累加进去
    }

    print(sum);                                     // 输出最终答案 1!+2!+...+n!
    return 0;
}
